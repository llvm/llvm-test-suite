"""Test module to collect compile-time metrics (time and peak memory). It
reads the *.test.o.time.list and *.test.link.time.list path-list files generated by
CMake at configure time and summarize the *.time files generated by the build
that are listed."""
from litsupport.modules import timeit
import os

def _sumTimeFiles(list_path):
    """Returns (summed user time, max RSS) of the .time files listed in
    list_path."""
    total_time = 0.0
    maxrss = 0
    if not os.path.isfile(list_path):
        return total_time, maxrss
    with open(list_path) as f:
        for line in f:
            path = line.rstrip("\n")
            if not path:
                continue
            try:
                with open(path) as fd:
                    contents = fd.read()
            except OSError:
                continue
            total_time += timeit.getUserTimeFromContents(contents)
            maxrss = max(maxrss, timeit.getMaxRSSFromContents(contents))
    return total_time, maxrss

def _getCompileTimeLegacy(context):
    # Fallback for tests without path-list files, e.g. test suites that do not
    # go through llvm_add_test_for_target().
    #
    # We compile multiple benchmarks in the same directory in SingleSource
    # mode. Only look at compiletime files starting with the name of our test.
    prefix = ""
    if context.config.single_source:
        prefix = "%s." % os.path.basename(context.executable)

    compile_time = 0.0
    link_time = 0.0
    compile_maxrss = 0
    link_maxrss = 0
    dir = os.path.dirname(context.test.getFilePath())
    for path, subdirs, files in os.walk(dir):
        for file in files:
            if file.endswith(".o.time") and file.startswith(prefix):
                fullpath = os.path.join(path, file)
                with open(fullpath) as fd:
                    contents = fd.read()
                compile_time += timeit.getUserTimeFromContents(contents)
                compile_maxrss = max(compile_maxrss,
                                     timeit.getMaxRSSFromContents(contents))
            elif file.endswith(".link.time") and file.startswith(prefix):
                fullpath = os.path.join(path, file)
                with open(fullpath) as fd:
                    contents = fd.read()
                link_time += timeit.getUserTimeFromContents(contents)
                link_maxrss = max(link_maxrss,
                                  timeit.getMaxRSSFromContents(contents))
    return {
        "compile_time": compile_time,
        "link_time": link_time,
        "compile_maxrss": compile_maxrss,
        "link_maxrss": link_maxrss,
    }

def _getCompileTime(context):
    test_path = context.test.getFilePath()
    o_time_list = test_path + ".o.time.list"
    link_time_list = test_path + ".link.time.list"
    if not (os.path.isfile(o_time_list) or os.path.isfile(link_time_list)):
        return _getCompileTimeLegacy(context)
    compile_time, compile_maxrss = _sumTimeFiles(o_time_list)
    link_time, link_maxrss = _sumTimeFiles(link_time_list)
    return {
        "compile_time": compile_time,
        "link_time": link_time,
        "compile_maxrss": compile_maxrss,
        "link_maxrss": link_maxrss,
    }

def mutatePlan(context, plan):
    plan.metric_collectors.append(_getCompileTime)
