"""Test module to collect compile-time metrics (time and peak memory). This
reads the *.compile_link_time summary file generated by the build-stage
aggregate-compile-time.py script."""
import os


def _parseSummary(contents):
    """Parse a compile_link_time summary file into a dict of key -> value."""
    result = {}
    for line in contents.splitlines():
        parts = line.split()
        if len(parts) == 2:
            key, raw = parts
            result[key] = float(raw) if "." in raw else int(raw)
    return result


def _getCompileTime(context):
    exe_name = os.path.basename(context.executable)
    test_dir = os.path.dirname(context.test.getFilePath())
    summary_file = os.path.join(test_dir, exe_name + ".compile_link_time")

    if not os.path.isfile(summary_file):
        return {
            "compile_time": 0.0,
            "link_time": 0.0,
            "compile_maxrss": 0,
            "link_maxrss": 0,
        }

    with open(summary_file) as f:
        data = _parseSummary(f.read())

    return {
        "compile_time":   data.get("compile_time", 0.0),
        "link_time":      data.get("link_time", 0.0),
        "compile_maxrss": data.get("compile_maxrss", 0),
        "link_maxrss":    data.get("link_maxrss", 0),
    }


def mutatePlan(context, plan):
    plan.metric_collectors.append(_getCompileTime)
